export interface CaptionTrackInfo {
  languageTag: string;
  label: string;
  url: string;
  vttUrl: string;
  isAutoGenerated: boolean;
}

export class CaptionTracksExtractor {
  /**
   * Extract caption tracks from YouTube player response
   */
  static extractCaptionTracks(playerResponse: any): CaptionTrackInfo[] {
    const tracks =
      playerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];

    const result: CaptionTrackInfo[] = [];

    for (const t of tracks) {
      const baseUrl = t.baseUrl;
      if (!baseUrl) continue;

      const languageTag = t.languageCode || 'und';
      const isAutoGenerated = t.kind === 'asr';

      let label =
        t.name?.runs?.map((r: any) => r.text).join('') ||
        t.name?.simpleText ||
        languageTag;

      if (isAutoGenerated && !label.toLowerCase().includes('auto')) {
        label = `${label} (tự động)`;
      }

      // Convert URL to VTT format by appending or setting fmt=vtt
      const vttUrl = this.toVttUrl(baseUrl);

      result.push({
        languageTag,
        label,
        url: baseUrl,
        vttUrl,
        isAutoGenerated,
      });
    }

    return result;
  }

  private static toVttUrl(rawUrl: string): string {
    try {
      const parsed = new URL(rawUrl);
      parsed.searchParams.set('fmt', 'vtt');
      return parsed.toString();
    } catch {
      return rawUrl.includes('?') ? `${rawUrl}&fmt=vtt` : `${rawUrl}?fmt=vtt`;
    }
  }
}
